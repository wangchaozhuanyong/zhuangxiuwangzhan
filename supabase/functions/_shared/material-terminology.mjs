export const normalizeMaterialTerm = value => String(value ?? "").trim().toLowerCase().replace(/[-_]+/g, " ").replace(/\s+/g, " ");
const chineseIndexes = Object.fromEntries(Object.entries(materialChineseSpecifications).map(([field, terms]) => [field,
  new Map(Object.entries(terms).flatMap(([source, target]) => [[normalizeMaterialTerm(source), target], [normalizeMaterialTerm(target), target]])),
]));
export function reviewedMaterialChineseTerm(field, value) {
  return chineseIndexes[field]?.get(normalizeMaterialTerm(value));
}
const indexes = Object.fromEntries(Object.entries(materialMalayTerms).map(([field, terms]) => [field,
  new Map(Object.entries(terms).flatMap(([source, target]) => [[normalizeMaterialTerm(source), target], [normalizeMaterialTerm(target), target]])),
]));
const sourceIndexes = Object.fromEntries(Object.entries(materialMalayTerms).map(([field, terms]) => [field,
  new Set(Object.keys(terms).map(normalizeMaterialTerm)),
]));

// Accept reviewed source terms and already-localized terms, so fallback data stays idempotent.
export function reviewedMaterialMalayTerm(field, value) {
  return indexes[field]?.get(normalizeMaterialTerm(value));
}

export function reviewedMaterialMalayText(value) {
  const matches = new Set(Object.keys(indexes).map(field => reviewedMaterialMalayTerm(field, value)).filter(Boolean));
  return matches.size === 1 ? [...matches][0] : undefined;
}

export function materialTerminologyIssues(record) {
  if (normalizeMaterialTerm(record.category) === "furniture") return []; // Separate furniture product catalog.
  return Object.entries({ category: "category", subcategory: "subcategory", material_type: "type", color: "color", texture: "texture" })
    .flatMap(([field, termField]) => {
      const value = record[field];
      // Color/texture may be intentionally unspecified; required category/type checks stay with the publisher.
      if (value == null || String(value).trim() === "") return [];
      const chineseReady = !(termField in chineseIndexes) || Boolean(reviewedMaterialChineseTerm(termField, value));
      return sourceIndexes[termField].has(normalizeMaterialTerm(value)) && chineseReady ? [] : [{ field, value: String(value) }];
    });
}

const fieldNames = { category: "Category", subcategory: "Subcategory", material_type: "Material type", color: "Color", texture: "Texture" };
export class MaterialTerminologyError extends Error {
  constructor(issues) {
    super(`Material specifications need reviewed Chinese and Malay terms: ${issues.map(issue => `${fieldNames[issue.field]}: ${issue.value}`).join("; ")}`);
    this.name = "MaterialTerminologyError";
    this.issues = issues;
  }
}

export function assertMaterialTerminology(record) {
  const issues = materialTerminologyIssues(record);
  if (issues.length) throw new MaterialTerminologyError(issues);
}
